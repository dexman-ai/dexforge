"""Generate the Rust reference dataset for the UR5 IK port.

Provenance for ``src/drivers/ur5/test_data.rs``. Reproduces the test data
required by the issue:

  1. Sample 500 valid SE(3) target poses (forward kinematics of random,
     in-limit joint configurations, guaranteeing reachability).
  2. Run the reference Python solver
     ``ssik.prebuilt.ur5_ik.solve(T, respect_limits=False)`` on each pose.
  3. Retain poses with >1 solution and emit ``(pose, solutions)`` pairs as a
     Rust ``static`` slice consumed by the ``#[cfg(test)]`` module.

Usage::

    pip install ssik
    python repos/dexforge-ur/rust/src/drivers/ur5/codegen/generate_test_data.py
    # writes …/ur5/test_data.rs (sibling of ik_solver.rs)

The RNG seed is fixed so regenerating the file is deterministic.
"""

import io
import os

import numpy as np
from ssik.prebuilt import ur5_ik

rng = np.random.default_rng(12345)
# joint limits from artifact
lims = [(-6.28318530717959,6.28318530717959),
        (-6.28318530717959,6.28318530717959),
        (-3.14159265358979,3.14159265358979),
        (-6.28318530717959,6.28318530717959),
        (-6.28318530717959,6.28318530717959),
        (-6.28318530717959,6.28318530717959)]

cases=[]
attempts=0
while len(cases) < 500 and attempts < 20000:
    attempts+=1
    q = np.array([rng.uniform(lo,hi) for lo,hi in lims])
    T = ur5_ik.fk(q)
    sols = ur5_ik.solve(T, respect_limits=False)
    if len(sols) > 1:
        qs = [list(map(float, s.q)) for s in sols]
        cases.append((T.reshape(-1).tolist(), qs))

print("attempts",attempts,"cases",len(cases))
ncounts={}
for _,qs in cases:
    ncounts[len(qs)]=ncounts.get(len(qs),0)+1
print("solution-count distribution:",ncounts)

# write rust test data file
out=io.StringIO()
out.write("// AUTO-GENERATED test data. Do not edit by hand.\n")
out.write("// Generated by codegen/generate_test_data.py from\n")
out.write("// ssik.prebuilt.ur5_ik.solve(T, respect_limits=False).\n")
out.write("// Each case: (4x4 row-major target_tf, &[expected q solutions]).\n")
out.write("pub static CASES: &[(&[f64; 16], &[[f64; 6]])] = &[\n")
for tf, qs in cases:
    out.write("    (&[")
    out.write(", ".join(repr(float(x)) for x in tf))
    out.write("], &[")
    for q in qs:
        out.write("[" + ", ".join(repr(float(x)) for x in q) + "], ")
    out.write("]),\n")
out.write("];\n")
data=out.getvalue()
# Script lives at …/ur5/codegen/; write test_data.rs next to ik_solver.rs.
dest=os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "test_data.rs"))
os.makedirs(os.path.dirname(dest), exist_ok=True)
with open(dest,"w") as f:
    f.write(data)
print("wrote", dest, "bytes", len(data))
