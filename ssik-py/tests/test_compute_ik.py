@pytest.mark.parametrize("flat16,expected_qs", CASES)
def test_solution_count_matches_reference(flat16, expected_qs):
    """Number of solutions returned must equal the reference count."""
    x, y, z, rot = _tf_from_flat(flat16)
    solutions = ssik_py.compute_ik(x, y, z, rot, "ur5")
    assert len(solutions) == len(expected_qs), (
        f"Expected {len(expected_qs)} solutions, got {len(solutions)}: {solutions}"
    )


@pytest.mark.parametrize("flat16,expected_qs", CASES)
def test_every_reference_solution_found(flat16, expected_qs):
    """Every expected solution must appear (mod 2*pi) among returned solutions."""
    x, y, z, rot = _tf_from_flat(flat16)
    solutions = ssik_py.compute_ik(x, y, z, rot, "ur5")
    for ref_q in expected_qs:
        assert any(_q_close_mod(sol, ref_q) for sol in solutions), (
            f"Reference solution {ref_q} not found in returned set {solutions}"
        )


def test_unsupported_arm_raises():
    """Requesting an unknown arm must raise ValueError."""
    rot = Rotation.from_matrix(np.eye(3))
    with pytest.raises(ValueError, match="unsupported arm"):
        ssik_py.compute_ik(0.0, 0.0, 0.0, rot, "kuka")


def test_unreachable_pose_returns_empty():
    """A pose far outside the workspace should return no solutions."""
    rot = Rotation.from_matrix(np.eye(3))
    solutions = ssik_py.compute_ik(100.0, 100.0, 100.0, rot, "ur5")
    assert solutions == []


def test_accepts_scipy_rotation():
    """Function must accept scipy Rotation objects without error."""
    flat16, _ = CASES[0]
    x, y, z, rot = _tf_from_flat(flat16)
    result = ssik_py.compute_ik(x, y, z, rot, "ur5")
    assert isinstance(result, list)
    assert all(len(q) == 6 for q in result)
