TWO_PI = 2.0 * math.pi
# Keep this in sync with DEDUP_TOL in ssik-py/src/lib.rs (which inherits it
# from ssik-rust's DEDUP_TOL = 1e-3).  If the Rust constant changes, update
# this value accordingly.
DEDUP_TOL = 1e-3


def _wrap_to_pi(a: float) -> float:
    """Wrap angle to (-pi, pi]."""
    return math.remainder(a, TWO_PI)


def _q_close_mod(a, b, tol: float = DEDUP_TOL) -> bool:
    """True if joint vectors a and b agree modulo 2*pi within tol."""
    return all(abs(_wrap_to_pi(ai - bi)) <= tol for ai, bi in zip(a, b))


def _tf_from_flat(flat16):
    """Return (x, y, z, Rotation) from a row-major 4x4 flat list."""
    m = np.array(flat16, dtype=float).reshape(4, 4)
    x, y, z = float(m[0, 3]), float(m[1, 3]), float(m[2, 3])
    rot = Rotation.from_matrix(m[:3, :3])
    return x, y, z, rot


