"""Generate the baked Rust constants for the Flexiv Rizon 4 7R IK port.

Provenance for ``src/drivers/rizon4/consts.rs``.

The Python artifact ``ssik.prebuilt.rizon4_ik`` solves the 7R Rizon 4 via
``jointlock.seven_r``: it locks joint 2 to each of 16 fixed samples, reverses
the resulting 6R sub-chain, and dispatches each to an inner ikgeo solver
(``husty_pfurner.general_6r`` for 15 samples, ``two_parallel`` for sample 8).
The locked/reversed sub-chain geometry is a pure function of the arm topology --
it does not depend on the target pose -- so we bake it once here.

This follows the pattern of ``scripts/generate_xarm7_consts.py``; both arms
belong to the ``jointlock.seven_r`` (non-SRS 7R) class and share the codegen.

Usage::

    pip install ssik
    python scripts/generate_rizon4_consts.py  # writes src/drivers/rizon4/consts.rs
"""

import os

import numpy as np
from ssik.kinematics.reverse import reverse_kinematic_chain
from ssik.prebuilt import rizon4_ik as REF
from ssik.solvers.jointlock.seven_r import _lock_joint

LOCK_IDX = REF._LOCK_IDX
LOCK_SAMPLES = np.array(REF._LOCK_SAMPLES, dtype=np.float64)
DISPATCH = list(REF._DISPATCH_CACHE)

KB = REF._build_kb()


def subchain_geom(qlock):
    sub = _lock_joint(KB, LOCK_IDX, float(qlock))
    rev = reverse_kinematic_chain(sub)
    axes = [rev.joints[i].axis.copy() for i in range(6)]
    tl = [rev.joints[i].T_left[:3, 3].copy() for i in range(6)]
    trR = rev.joints[-1].T_right[:3, :3].copy()
    trt = rev.joints[-1].T_right[:3, 3].copy()
    return axes, tl, trR, trt


GEOMS = [subchain_geom(LOCK_SAMPLES[i]) for i in range(16)]
AXES7 = [np.array(a, dtype=float) for a in REF._JOINT_AXES]
TL7 = [np.array(m, dtype=float) for m in REF._JOINT_T_LEFTS]
TR7 = [np.array(m, dtype=float) for m in REF._JOINT_T_RIGHTS]


def f(x):
    return repr(float(x))


def v3(a):
    return "[" + ", ".join(f(x) for x in a) + "]"


def main():
    out = []
    out.append("// AUTO-GENERATED baked KinBody constants. Do not edit by hand.")
    out.append("// Generated by scripts/generate_rizon4_consts.py from")
    out.append(f"// ssik.prebuilt.rizon4_ik (solver jointlock.seven_r, lock_idx={LOCK_IDX}).")
    out.append("//")
    out.append("// The 16 locked/reversed 6R sub-chains (SUB_*) are the inner-solver geometry;")
    out.append("// AXES7 / TL7 / TR7_* are the full 7R chain used for FK closure verification.")
    out.append("")
    out.append(
        f"/// Locked-joint sample schedule (np.linspace over joint-{LOCK_IDX} range, 16, endpoint excluded)."
    )
    out.append("pub const LOCK_SAMPLES: [f64; 16] = [")
    out.append("    " + ", ".join(f(x) for x in LOCK_SAMPLES) + ",")
    out.append("];")
    out.append("")
    out.append("/// Inner 6R solver per lock sample: 0 = husty_pfurner.general_6r, 1 = two_parallel.")
    kinds = [0 if "husty_pfurner" in d else 1 for d in DISPATCH]
    out.append("pub const SOLVER_KIND: [u8; 16] = [" + ", ".join(str(k) for k in kinds) + "];")
    out.append("")

    def emit(name, inner, extract):
        out.append(f"/// {name} -- per lock-sample reversed 6R sub-chain geometry.")
        out.append(f"pub const {name}: [{inner}; 16] = [")
        for i in range(16):
            out.append("    " + extract(i) + ",")
        out.append("];")
        out.append("")

    emit("SUB_AXES", "[[f64; 3]; 6]",
         lambda i: "[" + ", ".join(v3(GEOMS[i][0][j]) for j in range(6)) + "]")
    emit("SUB_TL", "[[f64; 3]; 6]",
         lambda i: "[" + ", ".join(v3(GEOMS[i][1][j]) for j in range(6)) + "]")
    emit("SUB_TRR", "[[f64; 3]; 3]",
         lambda i: "[" + ", ".join(v3(GEOMS[i][2][r]) for r in range(3)) + "]")
    emit("SUB_TRT", "[f64; 3]", lambda i: v3(GEOMS[i][3]))

    out.append("/// 7R joint axes (base frame at q = 0).")
    out.append("pub const AXES7: [[f64; 3]; 7] = [")
    for a in AXES7:
        out.append("    " + v3(a) + ",")
    out.append("];")
    out.append("")
    out.append("/// 7R per-joint T_left translations.")
    out.append("pub const TL7: [[f64; 3]; 7] = [")
    for M in TL7:
        out.append("    " + v3(M[:3, 3]) + ",")
    out.append("];")
    out.append("")
    out.append("/// 7R per-joint T_right rotation blocks (row-major 3x3).")
    out.append("pub const TR7_R: [[[f64; 3]; 3]; 7] = [")
    for M in TR7:
        out.append("    " + "[" + ", ".join(v3(M[:3, :3][r]) for r in range(3)) + "]" + ",")
    out.append("];")
    out.append("")
    out.append("/// 7R per-joint T_right translations.")
    out.append("pub const TR7_T: [[f64; 3]; 7] = [")
    for M in TR7:
        out.append("    " + v3(M[:3, 3]) + ",")
    out.append("];")
    out.append("")

    here = os.path.dirname(os.path.abspath(__file__))
    dest = os.path.join(here, "..", "src", "drivers", "rizon4", "consts.rs")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w") as fh:
        fh.write("\n".join(out))
    print("wrote", os.path.normpath(dest))


if __name__ == "__main__":
    main()
