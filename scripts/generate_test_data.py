"""Generate the Rust reference datasets for the ported `ssik` IK drivers.

Provenance for ``src/drivers/<arm>/test_data.rs``. For each supported arm this
reproduces the test data required by the issue:

  1. Sample up to 500 valid SE(3) target poses (forward kinematics of random,
     in-limit joint configurations, guaranteeing reachability).
  2. Run the reference Python solver
     ``ssik.prebuilt.<arm>_ik.solve(T, respect_limits=False)`` on each pose.
  3. Retain poses with >1 solution and emit ``(pose, solutions)`` pairs as a
     Rust ``static`` slice consumed by the ``#[cfg(test)]`` module.

Usage::

    pip install ssik
    python scripts/generate_test_data.py            # all arms
    python scripts/generate_test_data.py ur5 z1     # selected arms

The RNG seed is fixed so regenerating the files is deterministic.
"""

import importlib
import io
import os
import sys

import numpy as np

# Arms whose closed-form solver has been translated to Rust. Each entry maps the
# Rust driver directory (``src/drivers/<key>``) to its ``ssik.prebuilt`` module.
ARMS = {
    "ur5": "ssik.prebuilt.ur5_ik",
    "z1": "ssik.prebuilt.z1_ik",
    "puma560": "ssik.prebuilt.puma560_ik",
}

# Per-arm degrees of freedom (all currently-ported arms are 6-DOF).
DOF = 6


def generate(arm: str, module_name: str) -> None:
    mod = importlib.import_module(module_name)
    rng = np.random.default_rng(12345)
    lims = mod._JOINT_LIMITS

    cases = []
    attempts = 0
    while len(cases) < 500 and attempts < 20000:
        attempts += 1
        q = np.array([rng.uniform(lo, hi) for lo, hi in lims])
        T = mod.fk(q)
        sols = mod.solve(T, respect_limits=False)
        if len(sols) > 1:
            qs = [list(map(float, s.q)) for s in sols]
            cases.append((T.reshape(-1).tolist(), qs))

    ncounts = {}
    for _, qs in cases:
        ncounts[len(qs)] = ncounts.get(len(qs), 0) + 1
    print(f"[{arm}] attempts {attempts} cases {len(cases)} dist {ncounts}")

    out = io.StringIO()
    out.write("// AUTO-GENERATED test data. Do not edit by hand.\n")
    out.write("// Generated by scripts/generate_test_data.py from\n")
    out.write(f"// {module_name}.solve(T, respect_limits=False).\n")
    out.write("// Each case: (4x4 row-major target_tf, &[expected q solutions]).\n")
    out.write(f"pub static CASES: &[(&[f64; 16], &[[f64; {DOF}]])] = &[\n")
    for tf, qs in cases:
        out.write("    (&[")
        out.write(", ".join(repr(float(x)) for x in tf))
        out.write("], &[")
        for q in qs:
            out.write("[" + ", ".join(repr(float(x)) for x in q) + "], ")
        out.write("]),\n")
    out.write("];\n")
    data = out.getvalue()

    dest = os.path.join(
        os.path.dirname(__file__), "..", "src", "drivers", arm, "test_data.rs"
    )
    dest = os.path.normpath(dest)
    with open(dest, "w") as f:
        f.write(data)
    print(f"[{arm}] wrote {dest} bytes {len(data)}")


def main() -> None:
    selected = sys.argv[1:] or list(ARMS)
    for arm in selected:
        if arm not in ARMS:
            raise SystemExit(f"unknown arm '{arm}'; choose from {list(ARMS)}")
        generate(arm, ARMS[arm])


if __name__ == "__main__":
    main()
