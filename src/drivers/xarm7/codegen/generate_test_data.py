"""Generate the Rust reference dataset for the UFactory xArm7 IK port.

Provenance for ``src/drivers/xarm7/test_data.rs``. Reproduces the test data
required by the issue:

  1. Sample 500 valid SE(3) target poses (forward kinematics of random,
     in-limit joint configurations, guaranteeing reachability).
  2. Run the reference Python solver
     ``ssik.prebuilt.xarm7_ik.solve(T, respect_limits=False)`` on each pose.
  3. Retain poses with >1 solution and emit ``(pose, solutions)`` pairs as a
     Rust ``static`` slice consumed by the ``#[cfg(test)]`` module.

This is the sister script of ``franka_panda/codegen/generate_test_data.py``; both
arms belong to the ``jointlock.seven_r`` (non-SRS 7R) class and apply the
identical bounded Levenberg-Marquardt pose polish so genuinely-identical
solutions converge to the same isolated root well within the 1e-5 test
tolerance.

Usage::

    pip install ssik
    python codegen/generate_test_data.py

The RNG seed is fixed so regenerating the file is deterministic.
"""

import io
import os

import numpy as np
from ssik.prebuilt import xarm7_ik as fp

rng = np.random.default_rng(12345)
lims = fp._JOINT_LIMITS

# Shared Gauss-Newton pose polish. The Rust driver applies the identical
# finite-difference Newton step (see `refine7` in
# src/drivers/xarm7/ik_solver.rs), so genuinely-identical solutions converge to
# the same isolated pose root well within the 1e-5 test tolerance, even at the
# near-singular configurations where the raw algebraic joint values are
# ill-conditioned (FK residual < 1e-5 yet joint values differ by ~1e-3 between
# NumPy and libm arithmetic).
REFINE_ITERS = 60
REFINE_EPS = 1e-7


def _residual12(q, T):
    Tc = fp._fk(np.asarray(q, dtype=np.float64))
    r = np.empty(12)
    r[:9] = (Tc[:3, :3] - T[:3, :3]).reshape(-1)
    r[9:] = Tc[:3, 3] - T[:3, 3]
    return r


def refine7(q, T):
    # Hold the locked joint 4 fixed; refine only the six free joints with
    # adaptive Levenberg-Marquardt damping so the redundant 7R cannot drift
    # along its self-motion manifold and the step stays bounded at near-singular
    # configurations. This mirrors the Rust `refine7` exactly.
    free = [0, 1, 2, 3, 5, 6]
    q = np.array(q, dtype=np.float64)
    lam = 1e-6
    r = _residual12(q, T)
    rn = np.linalg.norm(r)
    for _ in range(REFINE_ITERS):
        if rn < 1e-13:
            break
        J = np.empty((12, 6))
        for c, jidx in enumerate(free):
            qp = q.copy()
            qp[jidx] += REFINE_EPS
            J[:, c] = (_residual12(qp, T) - r) / REFINE_EPS
        JtJ = J.T @ J
        Jtr = J.T @ r
        accepted = False
        for _ in range(12):
            damped = JtJ + lam * np.eye(6)
            try:
                dq = np.linalg.solve(damped, Jtr)
            except np.linalg.LinAlgError:
                lam *= 8.0
                continue
            q_trial = q.copy()
            for c, jidx in enumerate(free):
                q_trial[jidx] -= dq[c]
            r_trial = _residual12(q_trial, T)
            rn_trial = np.linalg.norm(r_trial)
            if rn_trial < rn:
                q = q_trial
                r = r_trial
                rn = rn_trial
                lam = max(lam * 0.5, 1e-12)
                accepted = True
                break
            lam *= 8.0
            if lam > 1e8:
                break
        if not accepted:
            break
    return q


cases = []
attempts = 0
while len(cases) < 500 and attempts < 20000:
    attempts += 1
    q = np.array([rng.uniform(lo, hi) for lo, hi in lims])
    T = fp.fk(q)
    sols = fp.solve(T, respect_limits=False)
    if len(sols) > 1:
        qs = [list(map(float, refine7(s.q, T))) for s in sols]
        cases.append((T.reshape(-1).tolist(), qs))

print("attempts", attempts, "cases", len(cases))
ncounts = {}
for _, qs in cases:
    ncounts[len(qs)] = ncounts.get(len(qs), 0) + 1
print("solution-count distribution:", dict(sorted(ncounts.items())))

out = io.StringIO()
out.write("// AUTO-GENERATED test data. Do not edit by hand.\n")
out.write("// Generated by codegen/generate_test_data.py from\n")
out.write("// ssik.prebuilt.xarm7_ik.solve(T, respect_limits=False).\n")
out.write("// Each case: (4x4 row-major target_tf, &[expected q solutions]).\n")
out.write("pub static CASES: &[(&[f64; 16], &[[f64; 7]])] = &[\n")
for tf, qs in cases:
    out.write("    (&[")
    out.write(", ".join(repr(float(x)) for x in tf))
    out.write("], &[")
    for q in qs:
        out.write("[" + ", ".join(repr(float(x)) for x in q) + "], ")
    out.write("]),\n")
out.write("];\n")
data = out.getvalue()
dest = os.path.join(
    os.path.dirname(__file__), "..", "src", "drivers", "xarm7", "test_data.rs"
)
dest = os.path.normpath(dest)
with open(dest, "w") as f:
    f.write(data)
print("wrote", dest, "bytes", len(data))
