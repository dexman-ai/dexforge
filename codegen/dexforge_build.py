"""``dexforge`` command-line interface — a rigid-body *driver compiler*.

``dexforge build`` is an **end-to-end** rigid-body dynamics compiler: point it at
a URDF and it translates the arm's full **kinematics and dynamics** into a
**stand-alone** Rust crate written *outside* the dexforge repository. It calls an
LLM to translate the analytical inverse kinematics and runs the symbolic dynamics
compiler (``codegen/generate_dynamics.py``) to derive the forward kinematics,
geometric Jacobian and — from the URDF's inertial data — gravity / mass-matrix /
Coriolis / inverse-dynamics. The emitted crate is fully self-contained: it copies
the shared math kernels and the per-arm driver sources into the target directory
and generates its own ``Cargo.toml`` + ``lib.rs``, so the result builds and runs
**without** the dexforge repository or the ``dexforge`` Python package.

This lets an OEM use dexforge as a one-shot URDF compiler for their hardware:
hand it a URDF, get back a minimal, zero-allocation ``#![no_std]`` crate exposing
the arm's kinematics (``fk`` / ``solve``) and dynamics that they can vendor
straight into firmware.

Typical usage::

    pip install dexforge

    # End-to-end: compile a kinematics + dynamics driver crate from a URDF.
    dexforge build --urdf my_arm.urdf --base base_link --ee tool0 -o ~/my_arm_ik
    cd ~/my_arm_ik && cargo build --release

    dexforge build --urdf my_arm.urdf --base base_link --ee tool0 \\
        -o ~/my_arm_ik --list   # preview, write nothing
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, NamedTuple, Optional, Sequence

# Shared, arm-agnostic numeric kernels copied verbatim into every driver crate
# (src/math/<name>.rs). The driver sources reference these as ``crate::math::*``,
# so preserving the module layout lets the copied files compile unchanged.
_MATH_MODULES = ("kinematics", "postprocess", "ssik_core", "tolerances")

# Driver sources may reference shared solver modules that live alongside the
# per-arm directories (``src/drivers/<module>.rs``, exposed as
# ``crate::drivers::<module>``). These are detected per-arm by scanning the
# driver sources, so URDF-derived drivers pull in whatever they actually use.
_SHARED_DRIVER_MODULES = ("rizon_common",)


class Export(NamedTuple):
    """A planned stand-alone driver crate for a single arm."""

    arm: str
    crate_name: str
    out_dir: Path
    # (absolute source, absolute destination) files copied verbatim.
    copies: List[tuple]
    # (absolute destination, file contents) files generated by dexforge.
    generated: List[tuple]
    # Shared ``crate::drivers::<module>`` modules this driver pulls in.
    shared_modules: List[str]

    def files(self) -> List[Path]:
        """Every destination path this export will write."""
        return [dst for _, dst in self.copies] + [dst for dst, _ in self.generated]


def default_crate_name(arm: str) -> str:
    """Default Rust crate name for an arm's driver (a valid crate identifier)."""
    return f"{arm}_ik_driver"


def find_repo_root(start: Optional[Path] = None) -> Path:
    """Locate the dexforge repository root (the source of driver/math files).

    Walks upward from *start* (the directory containing this module by default)
    until it finds a directory holding both ``Cargo.toml`` and ``src/math``.

    :raises FileNotFoundError: If no repository root is found.
    """
    here = start or Path(__file__).resolve().parent
    for candidate in (here, *here.parents):
        if (candidate / "Cargo.toml").is_file() and (candidate / "src" / "math").is_dir():
            return candidate
    raise FileNotFoundError(
        "could not locate the dexforge source tree (no parent directory contains "
        "both 'Cargo.toml' and 'src/math/'). Run 'dexforge build' from a dexforge "
        "checkout, or pass --repo-root."
    )


def _is_within(path: Path, parent: Path) -> bool:
    """Return ``True`` if *path* is *parent* or lives inside it."""
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def _cargo_toml(crate_name: str, arm: str) -> str:
    """Render the stand-alone crate's ``Cargo.toml``."""
    return f"""\
[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2021"
description = "Stand-alone analytical IK driver for the {arm} arm, compiled by dexforge."
license = "BSD-3-Clause"

# Self-contained: depends only on libm + nalgebra (no_std), never on the
# dexforge repository or the dexforge Python package.
[dependencies]
libm = "0.2"

[dependencies.nalgebra]
version = "0.33"
default-features = false
features = ["libm"]

[profile.release]
lto = true
codegen-units = 1
panic = "abort"
"""


def _lib_rs(crate_name: str, arm: str) -> str:
    """Render the stand-alone crate's ``src/lib.rs``."""
    return f"""\
//! Stand-alone `{arm}` rigid-body driver (kinematics + dynamics),
//! compiled by `dexforge build`.
//!
//! This crate is fully self-contained: it does not depend on the dexforge
//! repository or the `dexforge` Python package. It exposes the arm's `fk` and
//! `solve` entry points (re-exported at the crate root) alongside the symbolic
//! kinematics and dynamics (`generated_kinematics::{{fk, jacobian, gravity,
//! mass_matrix, coriolis, inverse_dynamics}}`, whichever the URDF supports), and
//! is `#![no_std]`, heap-free, and bounded-iteration throughout.
#![no_std]
#![forbid(unsafe_code)]

pub mod drivers;
pub mod math;

pub use drivers::{arm}::ik_solver::{{fk, solve, TolerancePolicy}};
// Symbolic forward kinematics, geometric Jacobian and rigid-body dynamics
// (gravity / mass matrix / Coriolis / inverse dynamics) compiled by
// `codegen/generate_dynamics.py`. Re-exported so consumers reach the full
// kinematics + dynamics suite at the crate root.
pub use drivers::{arm}::generated_kinematics;
"""


def _drivers_mod_rs(arm: str, shared_modules: Sequence[str]) -> str:
    """Render the stand-alone crate's ``src/drivers/mod.rs``."""
    lines = [
        "//! Driver module index (compiled by dexforge build).",
        "",
    ]
    for module in shared_modules:
        lines.append(f"pub mod {module};")
    lines.append(f"pub mod {arm};")
    return "\n".join(lines) + "\n"


def _shared_modules_used(driver_src: Path) -> List[str]:
    """Detect which shared ``crate::drivers::<module>`` modules *driver_src* uses.

    Scans the per-arm ``.rs`` sources for references to each known shared module
    so that any arm (including a freshly URDF-compiled one) pulls in exactly the
    shared solver modules it actually depends on.
    """
    sources = "\n".join(
        rs.read_text(encoding="utf-8") for rs in sorted(driver_src.glob("*.rs"))
    )
    return [m for m in _SHARED_DRIVER_MODULES if m in sources]


def plan_export(
    arm: str,
    out_dir: Path,
    repo_root: Path,
    crate_name: Optional[str] = None,
) -> Export:
    """Plan the stand-alone driver crate for *arm* at *out_dir*.

    Assembles the list of files to copy (shared math kernels, per-arm driver
    sources, and any shared solver modules the driver references) and the files
    dexforge generates (``Cargo.toml``, ``src/lib.rs``, ``src/drivers/mod.rs``).

    Works for any arm with a driver directory under ``src/drivers/<arm>/``
    (compiled from a URDF by the LLM-assisted generator).

    :raises FileNotFoundError: If an expected source directory is missing.
    """
    crate_name = crate_name or default_crate_name(arm)
    out_dir = out_dir.resolve()
    src = repo_root / "src"

    copies: List[tuple] = []

    # Shared math kernels: src/math/{mod,<modules>}.rs
    math_src = src / "math"
    if not math_src.is_dir():
        raise FileNotFoundError(f"missing math kernels: {math_src}")
    copies.append((math_src / "mod.rs", out_dir / "src" / "math" / "mod.rs"))
    for name in _MATH_MODULES:
        copies.append((math_src / f"{name}.rs", out_dir / "src" / "math" / f"{name}.rs"))

    # Per-arm driver sources: every .rs file in the driver directory.
    driver_src = src / "drivers" / arm
    if not driver_src.is_dir():
        raise FileNotFoundError(
            f"missing driver directory: {driver_src}. Compile this arm from a "
            f"URDF first (dexforge build --urdf <file> ...)."
        )
    for rs in sorted(driver_src.glob("*.rs")):
        copies.append((rs, out_dir / "src" / "drivers" / arm / rs.name))

    # Shared solver modules the driver actually references.
    shared_modules = _shared_modules_used(driver_src)
    for module in shared_modules:
        rc = src / "drivers" / f"{module}.rs"
        if not rc.is_file():
            raise FileNotFoundError(f"missing shared driver module: {rc}")
        copies.append((rc, out_dir / "src" / "drivers" / f"{module}.rs"))

    # Optional provenance: copy the source URDF (the OEM's hardware spec) if any.
    for urdf in sorted(driver_src.glob("*.urdf")):
        copies.append((urdf, out_dir / urdf.name))

    generated: List[tuple] = [
        (out_dir / "Cargo.toml", _cargo_toml(crate_name, arm)),
        (out_dir / "src" / "lib.rs", _lib_rs(crate_name, arm)),
        (out_dir / "src" / "drivers" / "mod.rs", _drivers_mod_rs(arm, shared_modules)),
    ]

    return Export(
        arm=arm,
        crate_name=crate_name,
        out_dir=out_dir,
        copies=copies,
        generated=generated,
        shared_modules=shared_modules,
    )


def write_export(export: Export) -> List[Path]:
    """Materialise an :class:`Export` on disk, returning the written paths."""
    for src, dst in export.copies:
        if not src.is_file():
            raise FileNotFoundError(f"missing source file: {src}")
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    for dst, content in export.generated:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(content, encoding="utf-8")
    return export.files()


def verify_crate(out_dir: Path) -> tuple:
    """Build the generated crate to prove it is standalone.

    :returns: ``(success, combined_output)``.
    """
    result = subprocess.run(
        ["cargo", "build", "--release"],
        capture_output=True,
        text=True,
        cwd=str(out_dir),
    )
    return result.returncode == 0, (result.stderr + result.stdout).strip()


def generate_driver_from_urdf(
    urdf: Path,
    base_link: str,
    ee_link: str,
    repo_root: Path,
    llm_options: Optional[Dict[str, str]] = None,
) -> tuple:
    """Translate a URDF into an in-repo driver via the LLM code generator.

    Drives ``codegen/ik_generator.py`` (which generates a ssik artifact from the
    URDF, calls the LLM to translate it into ``#![no_std]`` Rust, then builds and
    tests the result) so the driver lands under ``src/drivers/<arm>/`` and can be
    exported as a stand-alone crate. The arm name is derived from the URDF stem.

    :param urdf: Path to the source URDF file.
    :param base_link: Base link name passed to the generator.
    :param ee_link: End-effector link name passed to the generator.
    :param repo_root: dexforge source tree (provides the generator + kernels).
    :param llm_options: Optional ``{key,url,model,max_retries}`` overrides passed
        through to the generator (otherwise its env-var defaults apply).
    :returns: ``(success, arm_name, combined_output)``.
    """
    generator = repo_root / "codegen" / "ik_generator.py"
    if not generator.is_file():
        return False, urdf.stem, f"missing code generator: {generator}"

    arm = urdf.stem
    llm_options = llm_options or {}
    with tempfile.TemporaryDirectory(prefix="dexforge_build_") as work:
        cmd = [
            sys.executable,
            str(generator),
            "--urdf",
            str(urdf.resolve()),
            "--base",
            base_link,
            "--ee",
            ee_link,
            "--output-dir",
            work,
        ]
        for flag, key in (
            ("--llm-key", "key"),
            ("--llm-url", "url"),
            ("--llm-model", "model"),
            ("--max-retries", "max_retries"),
        ):
            value = llm_options.get(key)
            if value is not None:
                cmd += [flag, str(value)]

        # The generator imports its sibling modules (ik_build, ik_llm, …) by
        # bare name, so it must run with codegen/ on the path; invoking it as a
        # subprocess from there keeps it self-contained.
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join(
            filter(None, [str(generator.parent), env.get("PYTHONPATH", "")])
        )
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            cwd=str(repo_root),
            env=env,
        )
    return result.returncode == 0, arm, (result.stderr + result.stdout).strip()


def generate_dynamics_for_arm(
    arm: str,
    urdf: Optional[Path],
    repo_root: Path,
) -> tuple:
    """Compile the arm's full rigid-body kinematics + dynamics in-repo.

    dexforge is a rigid-body dynamics compiler, not just an IK one: after the
    LLM produces the IK driver, this drives ``codegen/generate_dynamics.py``
    against the driver's ssik artifact (under ``src/drivers/<arm>/<arm>_ik.py``)
    to derive — symbolically with SymPy — the exact forward kinematics and
    geometric Jacobian, emitted as ``#![no_std]`` Rust at
    ``src/drivers/<arm>/generated_kinematics.rs`` (the module the IK solver's FK
    delegates to). When *urdf* carries ``<inertial>`` blocks, the same pass also
    emits gravity / mass-matrix / Coriolis / inverse-dynamics so the exported
    crate ships the complete kinematics **and** dynamics suite.

    :param arm: Arm name whose in-repo driver was just generated.
    :param urdf: Source URDF (supplies link masses/inertias for dynamics); the
        dynamics functions are emitted only when it carries ``<inertial>`` data.
    :param repo_root: dexforge source tree (provides the dynamics compiler).
    :returns: ``(success, combined_output)``.
    """
    script = repo_root / "codegen" / "generate_dynamics.py"
    if not script.is_file():
        return False, f"missing dynamics compiler: {script}"

    artifact = repo_root / "src" / "drivers" / arm / f"{arm}_ik.py"
    if not artifact.is_file():
        return False, f"missing ssik artifact for dynamics: {artifact}"

    output = repo_root / "src" / "drivers" / arm / "generated_kinematics.rs"
    cmd = [
        sys.executable,
        str(script),
        "--artifact",
        str(artifact),
        "--arm",
        arm,
        "--output",
        str(output),
    ]
    if urdf is not None and urdf.is_file():
        cmd += ["--urdf", str(urdf.resolve())]

    result = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        cwd=str(repo_root),
    )
    return result.returncode == 0, (result.stderr + result.stdout).strip()


def _llm_options(args: argparse.Namespace) -> Dict[str, str]:
    """Collect LLM override options from parsed args (omitting unset values)."""
    options: Dict[str, str] = {}
    for attr, key in (
        ("llm_key", "key"),
        ("llm_url", "url"),
        ("llm_model", "model"),
        ("max_retries", "max_retries"),
    ):
        value = getattr(args, attr, None)
        if value is not None:
            options[key] = value
    return options


def _progress_line(step: int, total_steps: int, description: str) -> str:
    """Render a stable progress line for ``dexforge build`` steps."""
    percent = (step * 100) // total_steps
    return f"[dexforge] [{step}/{total_steps} | {percent}%] {description}"


def _build_from_urdf(args: argparse.Namespace, repo_root: Path, base: Path) -> int:
    """Handle ``dexforge build --urdf``: translate a URDF, then export the crate."""
    urdf = Path(args.urdf)
    if not urdf.is_file():
        print(f"[dexforge] ERROR: URDF file not found: {urdf}", file=sys.stderr)
        return 2
    if not args.base or not args.ee:
        print(
            "[dexforge] ERROR: --urdf requires --base and --ee (the URDF's base "
            "and end-effector link names).",
            file=sys.stderr,
        )
        return 2

    # Verify is a fourth step only when we're not in --list mode.
    total_steps = 4 if (args.verify and not args.list) else 3
    print(_progress_line(1, total_steps, f"translate {urdf.name} into an IK driver via the LLM …"))
    ok, arm, output = generate_driver_from_urdf(
        urdf, args.base, args.ee, repo_root, _llm_options(args)
    )
    if not ok:
        print(
            f"[dexforge] ERROR: URDF→driver translation failed:\n{output}",
            file=sys.stderr,
        )
        return 1
    print(f"[dexforge]   \u2713 generated '{arm}' driver under src/drivers/{arm}/.")

    print(_progress_line(2, total_steps, f"compile full kinematics + dynamics for '{arm}' …"))
    ok, output = generate_dynamics_for_arm(arm, urdf, repo_root)
    if not ok:
        print(
            f"[dexforge] ERROR: kinematics/dynamics compilation failed:\n{output}",
            file=sys.stderr,
        )
        return 1
    print(
        f"[dexforge]   \u2713 compiled FK, Jacobian and dynamics under "
        f"src/drivers/{arm}/."
    )

    return _export_arm(arm, repo_root, base, args, total_steps)


def _export_arm(
    arm: str,
    repo_root: Path,
    out_dir: Path,
    args: argparse.Namespace,
    total_steps: int,
) -> int:
    """Plan, optionally list, write, and verify the stand-alone crate for *arm*."""
    try:
        export = plan_export(arm, out_dir, repo_root, args.name)
    except FileNotFoundError as exc:
        print(f"[dexforge] ERROR: {exc}", file=sys.stderr)
        return 1

    if args.list:
        print(_progress_line(3, total_steps, f"display compile plan for '{export.arm}'"))
        print("[dexforge] compile plan (1 crate):")
        print(f"  {export.arm} -> {export.out_dir}")
        print(f"      crate '{export.crate_name}', {len(export.files())} file(s):")
        for path in export.files():
            print(f"        {path.relative_to(export.out_dir)}")
        return 0

    print(_progress_line(3, total_steps, f"export {export.arm} driver -> {export.out_dir}"))
    try:
        written = write_export(export)
    except FileNotFoundError as exc:
        print(f"[dexforge]   \u2717 {exc}", file=sys.stderr)
        return 1
    print(f"[dexforge]   wrote {len(written)} file(s); crate '{export.crate_name}'.")

    if args.verify:
        print(_progress_line(4, total_steps, "verify standalone build (cargo build --release) …"))
        ok, output = verify_crate(export.out_dir)
        if not ok:
            print(f"[dexforge]   \u2717 {export.arm} failed to build:\n{output}", file=sys.stderr)
            return 1
        print(f"[dexforge]   \u2713 {export.arm} builds standalone.")
    else:
        print(f"[dexforge]   \u2713 {export.arm} compiled (build not verified).")

    print(f"[dexforge] done: standalone driver crate under {export.out_dir}.")
    return 0


def _build(args: argparse.Namespace) -> int:
    try:
        repo_root = Path(args.repo_root).resolve() if args.repo_root else find_repo_root()
    except FileNotFoundError as exc:
        print(f"[dexforge] ERROR: {exc}", file=sys.stderr)
        return 1

    base = Path(args.output).resolve()

    # The whole point is to emit a driver *outside* dexforge; refuse to scribble
    # generated crates back into the source tree.
    if _is_within(base, repo_root):
        print(
            f"[dexforge] ERROR: --output {base} is inside the dexforge repository "
            f"({repo_root}). Choose a directory outside the repo: the generated "
            f"driver is meant to be self-contained.",
            file=sys.stderr,
        )
        return 2

    # End-to-end path: compile a driver straight from a URDF via the LLM.
    return _build_from_urdf(args, repo_root, base)


def build_parser() -> argparse.ArgumentParser:
    """Construct the top-level ``dexforge`` argument parser."""
    parser = argparse.ArgumentParser(
        prog="dexforge",
        description="dexforge — compile stand-alone rigid-body driver crates (kinematics + dynamics).",
    )
    subparsers = parser.add_subparsers(dest="command")

    build_p = subparsers.add_parser(
        "build",
        help="Compile a stand-alone kinematics + dynamics driver crate (outside the dexforge repo).",
        description=(
            "Compile an arm's full rigid-body kinematics and dynamics into a "
            "self-contained Rust crate written outside the dexforge repository. "
            "Point it at a URDF (--urdf, with --base and --ee) to translate new "
            "hardware end-to-end: an LLM translates the analytical IK and the "
            "symbolic compiler derives FK, the Jacobian and (from the URDF's "
            "inertial data) gravity/mass-matrix/Coriolis/inverse-dynamics. The "
            "generated crate does not depend on dexforge."
        ),
    )
    build_p.add_argument(
        "--output",
        "-o",
        required=True,
        metavar="DIR",
        help=(
            "Target directory for the generated crate. Must be outside the "
            "dexforge repository."
        ),
    )
    build_p.add_argument(
        "--urdf",
        required=True,
        metavar="URDF",
        help=(
            "Compile a driver end-to-end from this URDF file (calls the LLM to "
            "translate it). Requires --base and --ee."
        ),
    )
    build_p.add_argument(
        "--base",
        metavar="LINK",
        help="Base link name in the URDF (required with --urdf).",
    )
    build_p.add_argument(
        "--ee",
        metavar="LINK",
        help="End-effector link name in the URDF (required with --urdf).",
    )
    build_p.add_argument(
        "--name",
        metavar="CRATE",
        help="Override the generated crate name.",
    )
    build_p.add_argument(
        "--repo-root",
        metavar="DIR",
        help="Path to the dexforge source tree (auto-detected by default).",
    )
    build_p.add_argument(
        "--llm-key",
        metavar="KEY",
        help="LLM API key for --urdf translation (overrides DEXFORGE_LLM_KEY).",
    )
    build_p.add_argument(
        "--llm-url",
        metavar="URL",
        help="LLM base URL for --urdf translation (overrides DEXFORGE_LLM_BASE_URL).",
    )
    build_p.add_argument(
        "--llm-model",
        metavar="MODEL",
        help="LLM model for --urdf translation (overrides DEXFORGE_LLM_MODEL).",
    )
    build_p.add_argument(
        "--max-retries",
        metavar="N",
        type=int,
        help="Max LLM retry attempts for --urdf translation.",
    )
    build_p.add_argument(
        "--list",
        "--dry-run",
        dest="list",
        action="store_true",
        help="Print the compile plan without writing anything.",
    )
    build_p.add_argument(
        "--no-verify",
        dest="verify",
        action="store_false",
        help="Skip the standalone 'cargo build' verification of each crate.",
    )
    build_p.set_defaults(func=_build, verify=True)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI entry point used by the ``dexforge`` console script."""
    parser = build_parser()
    args = parser.parse_args(argv)
    if getattr(args, "func", None) is None:
        parser.print_help()
        return 1
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
