def generate_ik(
    urdf: Path,
    base_link: str,
    ee_link: str,
    repo_root: Path,
    output_dir: Path,
    oem_name: Optional[str] = None,
    max_retries: int = _MAX_RETRIES,
    llm_key: Optional[str] = None,
    llm_url: Optional[str] = None,
    llm_model: Optional[str] = None,
) -> tuple:
    """Core IK generator logic.

    Generates (or loads) a per-arm ssik artifact from a URDF, translates it
    into deterministic ``#![no_std]`` Rust via an LLM API, runs the companion
    Python helper scripts, then builds and tests the Rust crate. Build/test
    failures are fed back to the LLM so it can correct the code automatically.

    :param urdf: Path to the source URDF file (required).
    :param base_link: Base link name in the URDF (required).
    :param ee_link: End-effector link name in the URDF (required).
    :param output_dir: Working directory for the Python artifact and context dump.
    :param oem_name: OEM name for crate naming and provenance (default: URDF stem).
    :param repo_root: dexforge source tree root (provides kernels and driver paths).
    :param max_retries: Number of LLM retry attempts after the initial attempt.
    :param llm_key: LLM API key (overrides DEXFORGE_LLM_KEY env var).
    :param llm_url: LLM base URL (overrides DEXFORGE_LLM_BASE_URL env var).
    :param llm_model: LLM model name (overrides DEXFORGE_LLM_MODEL env var).
    :returns: ``(success, arm_name, error_message)``.  On success *error_message*
        is an empty string; progress is printed to stdout during execution.
    """
    # Lazy imports: these depend on ssik, openai, etc. which are not always
    # installed in environments that only need the export/packaging features.
    try:
        from ik_build import (
            build_and_verify,
            write_generated_files,
        )
        from ik_llm import (IKGeneratorLLM,  parse_llm_output)
        from ik_prompt import generate_context
    except ImportError:
        from codegen.ik_build import (  # type: ignore[no-redef]
            build_and_verify,
            write_generated_files,
        )
        from codegen.ik_llm import (IKGeneratorLLM,  parse_llm_output) # type: ignore[no-redef]
        from codegen.ik_prompt import generate_context  # type: ignore[no-redef]

    arm_name = urdf.stem if urdf is not None else ""
    oem_name = oem_name or arm_name
    error: Optional[str] = "LLM generation did not produce a buildable crate"

    # --- Step 0/1/2: artifact + family + context entrypoint ---
    try:
        entry = generate_context(
            urdf_path=urdf,
            base_link=base_link,
            ee_link=ee_link,
            output_dir=output_dir,
            repo_root=repo_root,
        )
        ssik_artifact = entry.ssik_artifact
        arm_name = entry.arm_name
        max_solutions = entry.max_solutions
        dof = entry.dof
        context = entry.context
    except (ImportError, FileNotFoundError, RuntimeError, ValueError) as exc:
        return False, arm_name, str(exc)

    # --- Step 4: Invoke LLM with retry loop ---
    print("[ik_generator] Step 4: Invoking LLM …")
    try:
        llm = IKGeneratorLLM(
            api_key=llm_key,
            base_url=llm_url,
            model=llm_model,
        )
    except ImportError as exc:
        return False, arm_name, str(exc)

    messages: list = [
        {"role": "system", "content": IKGeneratorLLM.SYSTEM_PROMPT},
        {"role": "user", "content": context},
    ]

    max_attempts = max_retries + 1

    for attempt in range(max_attempts):
        if attempt > 0:
            print(f"[ik_generator]   Retry {attempt}/{max_retries} …")

        try:
            raw_response = llm.generate(messages)
        except Exception as exc:  # noqa: BLE001 — surface all API errors
            return False, arm_name, f"LLM error ({type(exc).__name__}): {exc}"

        print(f"[ik_generator]   LLM response: {len(raw_response):,} chars.")

        # --- Step 5: Parse multi-file output ---
        try:
            files = parse_llm_output(raw_response)
        except ValueError as exc:
            if attempt < max_attempts - 1:
                messages.append({"role": "assistant", "content": raw_response})
                messages.append({
                    "role": "user",
                    "content": (
                        "Your output did not follow the required '=== FILE: <name> ===' "
                        "separator format. Please regenerate all files using the exact "
                        "output format specified in the prompt."
                    ),
                })
                continue
            return False, arm_name, f"Parse error: {exc}"

        print(
            f"[ik_generator]   Parsed {len(files)} file(s): "
            + ", ".join(files.keys())
        )

        if "arm.rs" not in files:
            files["arm.rs"] = generate_armmodel_impl(arm_name, dof, max_solutions)

        # --- Step 6: Write generated files ---
        print("[ik_generator] Step 6: Writing generated files …")
        written = write_generated_files(
            output_dir,
            oem_name,
            repo_root,
            arm_name,
            files,
            ssik_artifact,
            context,
            urdf,
        )

        # --- Step 6b: Symbolic FK/Jacobian/dynamics BEFORE cargo build ---
        # arm.rs / lib.rs re-export generated_kinematics + generated_dynamics;
        # those modules come from SymPy, not the LLM. Generate them once and
        # reuse across LLM retries so we do not pay the SymPy cost repeatedly.
        driver_dir = output_dir / "src" / "drivers" / arm_name
        dyn_rs = driver_dir / "generated_dynamics.rs"
        if not dyn_rs.is_file():
            print(
                f"[ik_generator] Step 6b: Compiling symbolic kinematics + "
                f"dynamics for '{arm_name}' …"
            )
            ok_dyn, dyn_msg = generate_dynamics_for_arm(
                arm_name, Path(urdf), output_dir, ssik_artifact=None
            )
            if not ok_dyn:
                return False, arm_name, dyn_msg
            print(f"[ik_generator]   ✓ {dyn_msg}")
        else:
            _wire_generated_dynamics_module(driver_dir)
            print(
                "[ik_generator] Step 6b: Reusing existing generated_dynamics.rs "
                "(skip SymPy on retry)."
            )

        # --- Step 6c: Pinocchio golden data + dynamics_parity before cargo test ---
        print(
            f"[ik_generator] Step 6c: Ensuring Pinocchio dynamics parity for "
            f"'{arm_name}' …"
        )
        ok_parity, parity_msg = ensure_dynamics_parity(
            arm_name, Path(urdf), output_dir
        )
        if not ok_parity:
            return False, arm_name, parity_msg
        print(f"[ik_generator]   ✓ {parity_msg}")

        # --- Step 7/8/9: scripts + build + test ---
        error = build_and_verify(
            generator_scripts=written,
            output_dir=output_dir,
        )
        if error is None:
            return True, arm_name, ""

        # on failure, append the error to the message history and retry
        messages.append({"role": "assistant", "content": raw_response})
        messages.append({
            "role": "user",
            "content": (
                f"The generated code failed to build or test with the following error:\n```\n{error}\n```\n"
                "Please fix the code to resolve this error and regenerate all files."
            ),
        })

    return False, arm_name, f"Build failure after {max_attempts} attempts: {error}"


