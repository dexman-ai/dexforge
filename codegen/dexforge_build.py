# Default number of LLM *retry* attempts after the initial attempt, so total
# LLM calls = _MAX_RETRIES + 1.
_MAX_RETRIES = 3

# Shared, arm-agnostic numeric kernels copied verbatim into every driver crate
# (src/math/<name>.rs). The driver sources reference these as ``crate::math::*``,
# so preserving the module layout lets the copied files compile unchanged.
_MATH_MODULES = ("kinematics", "postprocess", "ssik_core", "tolerances")

# Driver sources may reference shared solver modules that live alongside the
# per-arm driver directories (exposed as ``crate::drivers::<module>``). These
# are detected per-arm by scanning the driver sources, so URDF-derived drivers
# pull in whatever they actually use.
_SHARED_DRIVER_MODULES = ("rizon_common",)


class Export(NamedTuple):
    """A planned stand-alone driver crate for a single arm."""

    arm: str
    crate_name: str
    out_dir: Path
    # (absolute source, absolute destination) files copied verbatim.
    copies: List[tuple]
    # (absolute destination, file contents) files generated by dexforge.
    generated: List[tuple]
    # Shared ``crate::drivers::<module>`` modules this driver pulls in.
    shared_modules: List[str]

    def files(self) -> List[Path]:
        """Every destination path this export will write."""
        return [dst for _, dst in self.copies] + [dst for dst, _ in self.generated]


def default_crate_name(arm: str) -> str:
    """Default Rust crate name for an arm's driver (a valid crate identifier)."""
    return f"{arm}_ik_driver"


def find_repo_root(start: Optional[Path] = None) -> Path:
    """Locate the dexforge repository root (the source of driver/math files).

    Walks upward from *start* (the directory containing this module by default)
    until it finds a directory holding ``src/Cargo.toml`` and ``src/math``.

    :raises FileNotFoundError: If no repository root is found.
    """
    here = start or Path(__file__).resolve().parent
    for candidate in (here, *here.parents):
        if (candidate / "src" / "Cargo.toml").is_file() and (candidate / "src" / "math").is_dir():
            return candidate
    raise FileNotFoundError(
        "could not locate the dexforge source tree (no parent directory contains "
        "both 'src/Cargo.toml' and 'src/math/'). Run 'dexforge build' from a dexforge "
        "checkout, or pass --repo-root."
    )


def _is_within(path: Path, parent: Path) -> bool:
    """Return ``True`` if *path* is *parent* or lives inside it."""
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def _cargo_toml(crate_name: str, arm: str) -> str:
    """Render the stand-alone crate's ``Cargo.toml``."""
    return f"""\
[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2021"
description = "Stand-alone analytical IK driver for the {arm} arm, compiled by dexforge."
license = "BSD-3-Clause"

# Self-contained: depends only on libm + nalgebra (no_std), never on the
# dexforge repository or the dexforge Python package.
[dependencies]
libm = "0.2"

[dependencies.nalgebra]
version = "0.33"
default-features = false
features = ["libm"]

[profile.release]
lto = true
codegen-units = 1
panic = "abort"
"""


def _lib_rs(crate_name: str, arm: str) -> str:
    """Render the stand-alone crate's ``src/lib.rs``."""
    return f"""\
//! Stand-alone `{arm}` rigid-body driver (kinematics + dynamics),
//! compiled by `dexforge build`.
//!
//! This crate is fully self-contained: it does not depend on the dexforge
//! repository or the `dexforge` Python package. It exposes the arm's `fk` and
//! `solve` entry points (re-exported at the crate root) alongside the symbolic
//! kinematics and dynamics (`generated_kinematics::{{fk, jacobian, gravity,
//! mass_matrix, coriolis, inverse_dynamics}}`, whichever the URDF supports), and
//! is `#![no_std]`, heap-free, and bounded-iteration throughout.
#![no_std]
#![forbid(unsafe_code)]

pub mod drivers;
pub mod math;

pub use drivers::{arm}::ik_solver::{{fk, solve, TolerancePolicy}};
// Symbolic forward kinematics, geometric Jacobian and rigid-body dynamics
// (gravity / mass matrix / Coriolis / inverse dynamics) compiled by
// `dexforge build`. Re-exported so consumers reach the full
// kinematics + dynamics suite at the crate root.
pub use drivers::{arm}::generated_kinematics;
"""


def _drivers_mod_rs(arm: str, shared_modules: Sequence[str]) -> str:
    """Render the stand-alone crate's driver module index."""
    lines = [
        "//! Driver module index (compiled by dexforge build).",
        "",
    ]
    for module in shared_modules:
        lines.append(f"pub mod {module};")
    lines.append(f"pub mod {arm};")
    return "\n".join(lines) + "\n"


def _arm_marker_name(arm_name: str) -> str:
    """Render the Rust marker type name for an arm module."""
    return "".join(part[:1].upper() + part[1:] for part in arm_name.split("_") if part)


def generate_armmodel_impl(arm_name: str, dof: int, max_solutions: int) -> str:
    """Render the per-arm ``arm.rs`` module containing the ArmModel impl.

    The generated module owns the zero-sized marker type and the concrete
    ``ArmModel`` implementation for the arm's ``fk`` / ``jacobian`` /
    ``solve`` entry points.
    """
    marker_name = _arm_marker_name(arm_name)
    return f"""\
use crate::math::arm::{{ArmModel, Pose}};
use crate::math::tolerances::TolerancePolicy;

/// {marker_name} driver marker.
pub struct {marker_name};

impl ArmModel<{dof}, {max_solutions}> for {marker_name} {{
    #[inline]
    fn flange_fk(q: &[f64; {dof}]) -> Pose {{
        crate::drivers::{arm_name}::ik_solver::fk(q)
    }}

    #[inline]
    fn flange_jacobian(q: &[f64; {dof}]) -> [[f64; {dof}]; 6] {{
        crate::drivers::{arm_name}::generated_kinematics::jacobian(q)
    }}

    #[inline]
    fn flange_solve(
        target: &Pose,
        max_solutions: Option<usize>,
        q_seed: Option<&[f64; {dof}]>,
        respect_limits: bool,
        allow_refinement: bool,
        policy: TolerancePolicy,
        refinement_max_iters: usize,
    ) -> [Option<[f64; {dof}]>; {max_solutions}] {{
        crate::drivers::{arm_name}::ik_solver::solve(
            target,
            max_solutions,
            q_seed,
            respect_limits,
            allow_refinement,
            policy,
            refinement_max_iters,
        )
    }}
}}
"""


def _shared_modules_used(driver_src: Path) -> List[str]:
    """Detect which shared ``crate::drivers::<module>`` modules *driver_src* uses.

    Scans the per-arm ``.rs`` sources for references to each known shared module
    so that any arm (including a freshly URDF-compiled one) pulls in exactly the
    shared solver modules it actually depends on.
    """
    sources = "\n".join(
        rs.read_text(encoding="utf-8") for rs in sorted(driver_src.glob("*.rs"))
    )
    return [m for m in _SHARED_DRIVER_MODULES if m in sources]


def _driver_dir(repo_root: Path, arm: str) -> Path:
    """Return the canonical source path for an arm's driver directory."""
    return repo_root / "src" / "drivers" / arm


def plan_export(
    arm: str,
    out_dir: Path,
    repo_root: Path,
    crate_name: Optional[str] = None,
) -> Export:
    """Plan the stand-alone driver crate for *arm* at *out_dir*.

    Assembles the list of files to copy (shared math kernels, per-arm driver
    sources, and any shared solver modules the driver references) and the files
    dexforge generates the crate manifest, ``src/lib.rs``, and the driver module
    index.

    Works for any arm with a driver directory in the source tree (compiled from
    a URDF by the LLM-assisted generator).

    :raises FileNotFoundError: If an expected source directory is missing.
    """
    crate_name = crate_name or default_crate_name(arm)
    out_dir = out_dir.resolve()
    src = repo_root / "src"

    copies: List[tuple] = []

    # Shared math kernels: src/math/{mod,<modules>}.rs
    math_src = src / "math"
    if not math_src.is_dir():
        raise FileNotFoundError(f"missing math kernels: {math_src}")
    copies.append((math_src / "mod.rs", out_dir / "src" / "math" / "mod.rs"))
    for name in _MATH_MODULES:
        copies.append((math_src / f"{name}.rs", out_dir / "src" / "math" / f"{name}.rs"))

    # Per-arm driver sources: every .rs file in the driver directory.
    driver_src = _driver_dir(repo_root, arm)
    if not driver_src.is_dir():
        raise FileNotFoundError(
            f"missing driver directory: {driver_src}. Compile this arm from a "
            f"URDF first (dexforge build --urdf <file> ...)."
        )
    for rs in sorted(driver_src.glob("*.rs")):
        copies.append((rs, out_dir / "src" / "drivers" / arm / rs.name))

    # Shared solver modules the driver actually references.
    shared_modules = _shared_modules_used(driver_src)
    for module in shared_modules:
        rc = repo_root / "src" / "drivers" / f"{module}.rs"
        if not rc.is_file():
            raise FileNotFoundError(f"missing shared driver module: {rc}")
        copies.append((rc, out_dir / "src" / "drivers" / f"{module}.rs"))

    # Optional provenance: copy the source URDF (the OEM's hardware spec) if any.
    for urdf in sorted(driver_src.glob("*.urdf")):
        copies.append((urdf, out_dir / urdf.name))

    generated: List[tuple] = [
        (out_dir / "Cargo.toml", _cargo_toml(crate_name, arm)),
        (out_dir / "src" / "lib.rs", _lib_rs(crate_name, arm)),
        (out_dir / "src" / "drivers" / "mod.rs", _drivers_mod_rs(arm, shared_modules)),
    ]

    return Export(
        arm=arm,
        crate_name=crate_name,
        out_dir=out_dir,
        copies=copies,
        generated=generated,
        shared_modules=shared_modules,
    )


def write_export(export: Export) -> List[Path]:
    """Materialise an :class:`Export` on disk, returning the written paths."""
    for src, dst in export.copies:
        if not src.is_file():
            raise FileNotFoundError(f"missing source file: {src}")
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    for dst, content in export.generated:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(content, encoding="utf-8")
    return export.files()


def verify_crate(out_dir: Path) -> tuple:
    """Build the generated crate to prove it is standalone.

    :returns: ``(success, combined_output)``.
    """
    result = subprocess.run(
        ["cargo", "build", "--release"],
        capture_output=True,
        text=True,
        cwd=str(out_dir),
    )
    return result.returncode == 0, (result.stderr + result.stdout).strip()


# ===========================================================================
# Symbolic dynamics compiler (formerly generate_dynamics.py)
#
# Derives closed-form FK, geometric Jacobian and manipulator dynamics
# (gravity / mass-matrix / Coriolis / inverse-dynamics) symbolically with
# SymPy from a ssik kinematics artifact, then emits pure #![no_std] Rust.
# Heavy deps (numpy, sympy) are optional; _HAS_DYNAMICS_DEPS guards their use.
# ===========================================================================

# Tolerance for snapping a baked artifact float to the nearest integer.
_SNAP_TOL = 1e-12


# ---------------------------------------------------------------------------
# ssik artifact loading
# ---------------------------------------------------------------------------


def load_artifact(artifact: str) -> types.ModuleType:
    """Import a ssik artifact by prebuilt name or by path to a ``*_ik.py`` file."""
    candidate = Path(artifact)
    if candidate.exists():
        spec = importlib.util.spec_from_file_location(candidate.stem, candidate)
        if spec is None or spec.loader is None:
            raise ImportError(f"cannot load artifact module from {candidate}")
        mod = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = mod
        spec.loader.exec_module(mod)
        return mod

    name = artifact[:-3] if artifact.endswith(".py") else artifact
    try:
        return importlib.import_module(f"ssik.prebuilt.{name}")
    except ModuleNotFoundError as exc:
        raise ImportError(
            f"Cannot find {artifact!r} as a file or as ssik.prebuilt.{name}. "
            "Install ssik (`pip install ssik`) or pass a path to the artifact file."
        ) from exc


def _snap(value: float) -> sp.Expr:
    """Snap a baked float to an exact integer when within ``_SNAP_TOL``."""
    rounded = round(value)
    if abs(value - rounded) < _SNAP_TOL:
        return sp.Integer(rounded)
    return sp.Float(value, 17)


def _to_matrix(arr) -> sp.Matrix:
    a = np.asarray(arr, dtype=np.float64)
    return sp.Matrix([[_snap(a[i, j]) for j in range(a.shape[1])] for i in range(a.shape[0])])


def _to_vector(arr) -> sp.Matrix:
    a = np.asarray(arr, dtype=np.float64).reshape(-1)
    return sp.Matrix([_snap(x) for x in a])


def extract_chain(
    mod: types.ModuleType,
) -> Tuple[List[sp.Matrix], List[sp.Matrix], List[sp.Matrix], int]:
    """Pull the product-of-exponentials chain out of a ssik artifact.

    :returns: ``(t_lefts, axes, t_rights, dof)`` as cleaned SymPy objects.
    """
    try:
        axes_raw = mod._JOINT_AXES
        tl_raw = mod._JOINT_T_LEFTS
        tr_raw = mod._JOINT_T_RIGHTS
    except AttributeError as exc:
        raise ValueError(
            f"artifact {mod.__name__!r} does not expose the expected "
            "_JOINT_AXES / _JOINT_T_LEFTS / _JOINT_T_RIGHTS constants"
        ) from exc

    axes = [_to_vector(a) for a in axes_raw]
    t_lefts = [_to_matrix(m) for m in tl_raw]
    t_rights = [_to_matrix(m) for m in tr_raw]
    dof = int(getattr(mod, "DOF", len(axes)))
    if not (len(axes) == len(t_lefts) == len(t_rights) == dof):
        raise ValueError(
            f"inconsistent chain lengths: axes={len(axes)}, T_left={len(t_lefts)}, "
            f"T_right={len(t_rights)}, DOF={dof}"
        )
    return t_lefts, axes, t_rights, dof


def extract_base_ee_links(mod: types.ModuleType) -> Tuple[Optional[str], Optional[str]]:
    """Read the optional base and end-effector link names from an artifact."""
    base = getattr(mod, "BASE_LINK", None)
    ee = getattr(mod, "EE_LINK", None)
    return (base if isinstance(base, str) else None, ee if isinstance(ee, str) else None)


# ---------------------------------------------------------------------------
# Symbolic SE(3) construction
# ---------------------------------------------------------------------------


def _axis_angle_rot(axis: sp.Matrix, angle: sp.Expr) -> sp.Matrix:
    """Homogeneous Rodrigues rotation about a (constant) ``axis`` by ``angle``."""
    x, y, z = axis
    c, s = sp.cos(angle), sp.sin(angle)
    oc = 1 - c
    r = sp.Matrix(
        [
            [c + x * x * oc, x * y * oc - z * s, x * z * oc + y * s],
            [y * x * oc + z * s, c + y * y * oc, y * z * oc - x * s],
            [z * x * oc - y * s, z * y * oc + x * s, c + z * z * oc],
        ]
    )
    m = sp.eye(4)
    m[:3, :3] = r
    return m


def build_fk(
    t_lefts: List[sp.Matrix], axes: List[sp.Matrix], t_rights: List[sp.Matrix]
) -> Tuple[sp.Matrix, List[sp.Symbol], List[sp.Matrix]]:
    """Build the symbolic base->ee transform from the ssik chain.

    :returns: ``(T_ee, q_syms, frames)`` where ``frames[i]`` is the base->joint-i
        axis frame transform.
    """
    q_syms: List[sp.Symbol] = []
    frames: List[sp.Matrix] = []
    t_cum = sp.eye(4)
    for i, (tl, axis, tr) in enumerate(zip(t_lefts, axes, t_rights)):
        q = sp.Symbol(f"q{i}")
        q_syms.append(q)
        frame = t_cum * tl
        frames.append(frame)
        t_cum = frame * _axis_angle_rot(axis, q) * tr
    return t_cum, q_syms, frames


def build_jacobian(
    t_ee: sp.Matrix, axes: List[sp.Matrix], frames: List[sp.Matrix]
) -> sp.Matrix:
    """Geometric Jacobian ``[Jv; Jw]`` (6 x N) for the all-revolute ssik chain."""
    p_e = t_ee[:3, 3]
    cols = []
    for axis, frame in zip(axes, frames):
        r = frame[:3, :3]
        p_i = frame[:3, 3]
        z_i = r * axis
        jv = z_i.cross(p_e - p_i)
        jw = z_i
        cols.append(sp.Matrix.vstack(jv, jw))
    return sp.Matrix.hstack(*cols)


